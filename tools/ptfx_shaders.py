"""The pixel shaders of the game's particle effects, by the digest every compiled shader carries (a DXBC container's
bytes 4..20), for the loader to know the pipelines the game draws its particles with (src/loader/graphics/particles.cpp).
The game's shaders are in update2.rpf common/shaders/fxdb/sga_win32_60_final.awc (an "SGD2" container: per program
a u8 name length, the name, a u8 0x32, a u32 size, the DXBC container, then the names the program uses - its constant
buffers and their variables, samplers, textures - up to the next program; the programs grouped by kind, then by effect).
A particle shader is one whose names include a particle effect's constant buffers (ptfx_*, rmptfx_*, ptxgpu_*), and every
pixel shader named as the particle effects name theirs (PS_RGB*, PS_none*, PS_proj*, ...) next to one in the container:
some of an effect's shaders use none of its own constant buffers (PS_RGBA_litBM0, a lit sprite of smoke).
usage: ptfx_shaders.py <sga_win32_60_final.awc> <out .inc>   (ue5export extract --file ...sga_win32_60_final.awc)"""
import re, struct, sys

MARKERS = (b"ptfx_", b"rmptfx_", b"ptxgpu_")
NAMES = ("PS_RGB", "PS_none", "PS_proj", "PS_SoftnessHack", "PS_Draw", "PS_ptxgpu")


def programs(data):
    """(name, digest, the names after it) of each program."""
    found = []  # (header start, name, container start)
    for m in re.finditer(b"DXBC", data):
        at = m.start()
        if data[at - 5] not in (0x32, 0x41, 0x42) or struct.unpack_from("<I", data, at - 4)[0] != struct.unpack_from("<I", data, at + 24)[0]:
            continue  # (the bytes "DXBC" inside something else)
        end = at - 5
        for p in range(end - 2, max(end - 256, 0), -1):
            if data[p] == end - p - 1 and data[end - 1] == 0:
                found.append((p, data[p + 1:end - 1].decode("latin1"), at))
                break
    out = []
    for k, (start, name, at) in enumerate(found):
        size = struct.unpack_from("<I", data, at + 24)[0]
        tail_end = found[k + 1][0] if k + 1 < len(found) else len(data)
        out.append((name, data[at + 4:at + 20], data[at + size:min(tail_end, at + size + 65536)]))
    return out


def main():
    data = open(sys.argv[1], "rb").read()
    if data[:4] != b"SGD2":
        raise SystemExit("not an SGD2 container")
    every = programs(data)
    pixel = [(n, d, t) for n, d, t in every if n.startswith("PS_")]
    marked = [any(m in t for m in MARKERS) or "ptxgpu" in n for n, d, t in pixel]
    named = [n.startswith(NAMES) for n, d, t in pixel]
    # (runs of shaders named as the particle effects' that hold one known by its constant buffers)
    chosen = set()
    i = 0
    while i < len(pixel):
        if not named[i] and not marked[i]:
            i += 1
            continue
        j = i
        while j < len(pixel) and (named[j] or marked[j]):
            j += 1
        if any(marked[i:j]):
            chosen.update(range(i, j))
        i = j
    particle = sorted({(pixel[k][1], pixel[k][0]) for k in chosen})
    digests = [d for d, _ in particle]
    if len(set(digests)) != len(digests) or any(d == bytes(16) for d in digests):
        raise SystemExit("digests not unique")
    with open(sys.argv[2], "w", newline="\n") as out:
        out.write(f"// Generated by tools/ptfx_shaders.py: {len(particle)} of the game's {len(pixel)} pixel shaders ({len(every)} programs).\n")
        for d, n in particle:
            lo, hi = struct.unpack("<QQ", d)
            out.write(f"{{0x{lo:016x}, 0x{hi:016x}}}, // {n}\n")
    print(f"{len(every)} programs, {len(pixel)} pixel shaders, {len(particle)} of particles -> {sys.argv[2]}")


if __name__ == "__main__":
    main()
